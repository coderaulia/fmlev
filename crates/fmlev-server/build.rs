//! Embeds the web UI. `src/ui/manifest.json` lists the style, page and script files in load order;
//! this generates `include_str!` entries for them so adding a UI file never needs a Rust edit.
use std::{env, fs, path::Path};

fn main() {
    let root = Path::new(&env::var("CARGO_MANIFEST_DIR").unwrap()).join("src/ui");
    let manifest_path = root.join("manifest.json");
    println!("cargo:rerun-if-changed={}", manifest_path.display());
    println!("cargo:rerun-if-changed={}", root.join("index.html").display());
    let manifest: serde_json::Value =
        serde_json::from_str(&fs::read_to_string(&manifest_path).expect("read src/ui/manifest.json")).expect("valid manifest.json");
    let mut out = String::from("// @generated by build.rs from src/ui/manifest.json\n");
    for group in ["styles", "pages", "scripts"] {
        out.push_str(&format!("pub static {}: &[(&str, &str)] = &[\n", group.to_uppercase()));
        for file in manifest[group].as_array().unwrap_or_else(|| panic!("manifest.{group} must be a list")) {
            let file = file.as_str().expect("manifest entries are strings");
            let path = root.join(file);
            assert!(path.is_file(), "manifest lists missing UI file {file}");
            println!("cargo:rerun-if-changed={}", path.display());
            out.push_str(&format!("    ({file:?}, include_str!({:?})),\n", path.display().to_string()));
        }
        out.push_str("];\n");
    }
    fs::write(Path::new(&env::var("OUT_DIR").unwrap()).join("ui_bundle.rs"), out).unwrap();
}
